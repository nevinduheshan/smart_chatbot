def extract_clean_text(output):
    """LangChain / Gemini වලින් ලැබෙන Raw Response එක පිරිසිදු Text එකක් බවට පත් කිරීම"""
    if isinstance(output, str):
        return output
    elif isinstance(output, list):
        # List එකක් ආවොත් ඒක ඇතුළේ තියෙන 'text' කොටස විතරක් තෝරා ගැනීම
        return "\n\n".join([str(item.get("text", item)) if isinstance(item, dict) else str(item) for item in output])
    elif isinstance(output, dict) and "text" in output:
        return output["text"]
    return str(output)

