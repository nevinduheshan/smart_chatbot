def safe_parse_json(content):
    """Safely parse JSON outputs generated by LLMs."""
    if hasattr(content, "content"):
        raw_text = content.content
    else:
        raw_text = content

    if isinstance(raw_text, list):
        text_str = "\n".join([str(item.get("text", item)) if isinstance(item, dict) else str(item) for item in raw_text])
    else:
        text_str = str(raw_text)

    text_str = re.sub(r"```(?:json)?", "", text_str, flags=re.IGNORECASE).strip()
    json_match = re.search(r"\{.*\}", text_str, re.DOTALL)
    if json_match:
        text_str = json_match.group(0)

    try:
        return json.loads(text_str)
    except Exception:
        return {"extracted_text": text_str[:1000]}

def init_sql_db():
    """Initialize SQLite DB for storing structured website metadata/JSON."""
    conn = sqlite3.connect("website_data.db")
    # conn = sqlite3.connect("website_data_old.db")
    cursor = conn.cursor()
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS website_pages (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            url TEXT UNIQUE,
            title TEXT,
            extracted_json TEXT
        )
    """)
    conn.commit()
    conn.close()

init_sql_db()

def crawl_and_index_website(target_url):
    """Scrape entire website using Firecrawl, split content, and populate Vector DB & Hybrid Retriever."""
    st.info(f"🚀 Crawling website pages for `{target_url}` via Firecrawl. Please wait, this might take a few minutes...")
    
    try:
        # Firecrawl
        crawl_result = firecrawl_app.crawl(
            url=target_url,
            limit=20, 
            poll_interval=2, 
            scrape_options={'formats': ['markdown']},
            exclude_paths=['*/reports/*', '*/annual-report/*']
        )
    except AttributeError:
        # යම් හෙයකින් පරණ Firecrawl SDK එකක් නම් මේ Fallback එක වැඩ කරයි
        try:
            crawl_result = firecrawl_app.crawl_url(
                target_url,
                params={'scrapeOptions': {'formats': ['markdown']}}
            )
        except Exception as inner_e:
            st.error(f"❌ Firecrawl SDK Error: {inner_e}")
            return None
    except Exception as e:
        st.error(f"❌ Crawl Request Error: {e}")
        return None

    documents = []
    conn = sqlite3.connect("website_data.db")
    # conn = sqlite3.connect("website_data_old.db")

    cursor = conn.cursor()
    llm = ChatGoogleGenerativeAI(model="gemini-3.5-flash-lite", temperature=0, timeout=120, max_retries=5)

    # API එකෙන් ලැබෙන Data List එක වෙන් කර ගැනීම
    if isinstance(crawl_result, dict):
        page_data_list = crawl_result.get("data", [])
    else:
        page_data_list = getattr(crawl_result, "data", [])

    # Data මොකුත්ම ඇවිත් නැත්නම් Error එක හරියටම පෙන්නීම
    if not page_data_list:
        st.error(f"❌ Failed to scrape content from {target_url}.")
        st.warning("🔍 Firecrawl API එකෙන් ලැබුණු පිළිතුර (Error Reason):")
        # මේකෙන් ඔයාට හරියටම බලාගන්න පුළුවන් ඇයි fail වුණේ කියලා (උදා: Blocked by Cloudflare, Invalid URL)
        st.json(crawl_result if isinstance(crawl_result, dict) else str(crawl_result))
        return None

    for page in page_data_list:
        if isinstance(page, dict):
            markdown_text = page.get("markdown", "")
            page_url = page.get("metadata", {}).get("sourceURL", target_url)
            page_title = page.get("metadata", {}).get("title", "Web Page")
        else:
            markdown_text = getattr(page, "markdown", "")
            metadata = getattr(page, "metadata", {})
            page_url = getattr(metadata, "source_url", target_url) if hasattr(metadata, "source_url") else target_url
            page_title = getattr(metadata, "title", "Web Page") if hasattr(metadata, "title") else "Web Page"

        if markdown_text:
            doc = Document(
                page_content=markdown_text,
                metadata={
                    "source_url": page_url,
                    "title": page_title
                }
            )
            documents.append(doc)

            # Extract Structured Summary into SQL DB
            json_prompt = (
                "Extract a structured JSON summary for this web page.\n"
                "If this is the main homepage or services page, explicitly look for the 'Services We Offer' section cards.\n\n"
                "Return JSON format:\n"
                "{\n"
                '  "main_services": ["Strategic content and storytelling", "Advisory on global frameworks...", "Investor-grade design...", "Digital-first HTML reports...", "Video annual reports"],\n'
                '  "contact_phone": ["+94 77 395 0883", "+94 77 799 9921"],\n'
                '  "contact_email": ["info@SmartAnnualReport.com"],\n'
                '  "page_summary": "Brief summary"\n'
                "}\n\n"
                f"Title: {page_title}\nContent:\n{markdown_text[:12000]}"
            )
            try:
                response = llm.invoke(json_prompt)
                extracted_json = safe_parse_json(response)
                cursor.execute(
                    "INSERT OR REPLACE INTO website_pages (url, title, extracted_json) VALUES (?, ?, ?)",
                    (page_url, page_title, json.dumps(extracted_json))
                )
                conn.commit()
            except Exception as e:
                st.warning(f"Could not extract JSON for {page_url}: {e}")

    conn.close()

    if not documents:
        st.error("❌ Website crawled, but no text content was found on the pages.")
        return None

    # Text Chunking
    text_splitter = RecursiveCharacterTextSplitter(chunk_size=1500, chunk_overlap=300)
    splits = text_splitter.split_documents(documents)

    # Save Chunks to Vector DB
    persist_dir = "./chroma_db_website"
    # persist_dir = "./chroma_db_website_old"
    embeddings = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")
    vectorstore = Chroma.from_documents(documents=splits, embedding=embeddings, persist_directory=persist_dir)

    # Setup Hybrid Search
    dense_retriever = vectorstore.as_retriever(search_kwargs={"k": 30})
    bm25_retriever = BM25Retriever.from_documents(splits)
    bm25_retriever.k = 30

    try:
        hybrid_retriever = EnsembleRetriever(
            retrievers=[bm25_retriever, dense_retriever],
            weights=[0.5, 0.5]
        )
    except Exception:
        # Fallback if EnsembleRetriever fails
        hybrid_retriever = dense_retriever

    st.success(f"✅ Indexed {len(documents)} pages and {len(splits)} chunks successfully!")
    return hybrid_retriever

