@tool
def search_website_content(query: str) -> str:
    """Use this tool to perform a deep Reranked Hybrid Search across the indexed website pages."""
    if not st.session_state.retriever:
        return "No website has been indexed yet. Please scrape a website first."

    initial_docs = st.session_state.retriever.invoke(query)
    if not initial_docs:
        return "No relevant website content found."

    doc_contents = [doc.page_content for doc in initial_docs]

    try:
        # Cohere Direct API Reranking
        rerank_response = cohere_client.rerank(
            model="rerank-v3.0",
            query=query,
            documents=doc_contents,
            top_n=5
        )
        
        results = []
        for hit in rerank_response.results:
            doc = initial_docs[hit.index]
            url = doc.metadata.get("source_url", "N/A")
            title = doc.metadata.get("title", "Page")
            results.append(f"[Source: {title} ({url})]\n{doc.page_content}")

        return "\n\n---\n\n".join(results)

    except Exception:
        results = []
        for doc in initial_docs[:5]:
            url = doc.metadata.get("source_url", "N/A")
            results.append(f"[Source: {url}]\n{doc.page_content}")
        return "\n\n---\n\n".join(results)

@tool
def query_structured_sql_data(query: str) -> str:
    """Use this tool to read structured summaries of indexed website pages."""
    try:
        conn = sqlite3.connect("website_data.db")
        # conn = sqlite3.connect("website_data_old.db")

        cursor = conn.cursor()
        cursor.execute("SELECT url, title, extracted_json FROM website_pages")
        rows = cursor.fetchall()
        conn.close()

        if not rows:
            return "No structured data available."

        output = "Structured Web Page Data:\n\n"
        for row in rows:
            output += f"URL: {row[0]} | Title: {row[1]}\nSummary: {row[2]}\n\n"
        return output
    except Exception as e:
        return f"Error reading database: {e}"

tools = [search_website_content, query_structured_sql_data]

